function escapeGuruHtml(text) {
    return String(text || "")
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;");
}

function renderGuruTable() {
    var tbody = document.getElementById("guru-tbody");
    var badge = document.getElementById("guru-count-badge");
    var searchEl = document.getElementById("guru-search-input");
    var filterEl = document.getElementById("guru-filter-jabatan");
    if (!tbody) return;

    var query = searchEl ? searchEl.value.trim().toLowerCase() : "";
    var filterVal = filterEl ? filterEl.value : "semua";

    var filtered = dataGuruMAN1.filter(function (guru) {
        var strJab = (guru.jabatanStruktural || "").trim();
        var tamJab = (guru.jabatanTambahan || "").trim();
        var hasStruktural = strJab !== "" && strJab !== "-" && strJab !== "—";
        var hasTambahan = tamJab !== "" && tamJab !== "-" && tamJab !== "—";

        if (filterVal === "struktural" && !hasStruktural) return false;
        if (filterVal === "tambahan" && !hasTambahan) return false;

        if (!query) return true;
        var combined = [
            guru.namaGelar || "",
            guru.mapel || "",
            strJab,
            tamJab
        ].join(" ").toLowerCase();
        return combined.indexOf(query) !== -1;
    });

    if (badge) {
        badge.textContent = filtered.length + " dari " + dataGuruMAN1.length + " Guru Ditampilkan";
    }

    if (filtered.length === 0) {
        tbody.innerHTML = '<tr><td colspan="5" class="p-6 text-center text-slate-400">Belum ada data guru yang cocok dengan pencarian atau filter.</td></tr>';
        return;
    }

    tbody.innerHTML = filtered.map(function (guru, idx) {
        var strJab = guru.jabatanStruktural && guru.jabatanStruktural.trim() !== "-" && guru.jabatanStruktural.trim() !== "—"
            ? escapeGuruHtml(guru.jabatanStruktural)
            : '<span class="text-slate-500">—</span>';
        var tamJab = guru.jabatanTambahan && guru.jabatanTambahan.trim() !== "-" && guru.jabatanTambahan.trim() !== "—"
            ? escapeGuruHtml(guru.jabatanTambahan)
            : '<span class="text-slate-500">—</span>';
        var mapelText = guru.mapel && guru.mapel.trim() !== "-" && guru.mapel.trim() !== "—"
            ? escapeGuruHtml(guru.mapel)
            : '<span class="text-slate-500">—</span>';

        return (
            '<tr class="hover:bg-navy-900/60 transition">' +
                '<td class="p-3.5 text-center font-bold text-slate-400">' + (idx + 1) + '</td>' +
                '<td class="p-3.5 font-bold text-white">' + escapeGuruHtml(guru.namaGelar) + '</td>' +
                '<td class="p-3.5 text-slate-300">' + mapelText + '</td>' +
                '<td class="p-3.5 text-electric-300 font-semibold">' + strJab + '</td>' +
                '<td class="p-3.5 text-emerald-300 font-semibold">' + tamJab + '</td>' +
            '</tr>'
        );
    }).join("");
}

document.addEventListener("DOMContentLoaded", renderGuruTable);